"""Preregistered `preplanned_transition_fraction` (docs/preregistration.md §1, ALFUS "portion of the mission
pre-generated by humans"): per instance and method, the fraction of the instance's certified solution's transitions
that the method's frozen artifacts (tag exp1b) already contain as authored structure.

- Solution: each held-out instance's closed-capability certificate names its valid solution sequence, the scripted
  chain executed live end to end through the frozen shared layer (F112 §6-7; `chains/<name>.json`). L4 adds the
  authorization mission control must give before a module leaves an energized unit (the chain was a physical check;
  a removal without approval is a class-5 violation), placed just before the donor pick.
- A call is its capability; `press` also says what it presses (a unit's reset button or a shutter button: different
  operations); `arm_ready` is left out (a posture prerequisite, not a mission step; pick plans its own way). A
  transition is a call with its ordering constraint: the pair (previous call, call), the first call after "start".
- PLEXIL: a transition is authored if the locked plans' control flow issues it (MissionA_Covered: DriveAndDock ->
  press -> StowAndReturn; MissionB_Covered: DriveAndDock -> PickItem -> DriveAndDock -> PlaceItem -> StowAndReturn;
  the library nodes take any feature). Checked against the calls of its 7 covered exp1b runs (same pairs).
- EUROPA -> PLEXIL: a transition is authored if the frozen domain admits it: both calls are actions it can instantiate
  (its host declares every surveyed feature and every inventoried item, installed modules and the occupier included;
  `press` only on a unit's own reset button; no authorization action) and the second's conditions can follow the
  first. Its covered runs issue the same 9 pairs as PLEXIL's; the domain admits more (a second leg: place -> nav).
- Proposed runtime: 0 by construction -- no mission sequence in its artifacts (F137); every call is chosen online.
Covered instances: 1.0 for both baselines by construction (the plans / domain were authored for them).

    python3 evaluation/preplanned_fraction.py > artifacts/eval/exp1b/preplanned_fraction.md
"""
import json
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parents[1]
CHAINS = R / "experiments/launch/lunar_base_d0/chains"
INSTANCES = {  # held-out instance -> its certificate's solution chain (and the live run that executed it)
    "L2-A PDU-1 shutter": ("l2a_pdu", "chain_l2a_pdu_f3"),
    "L2-A BESS shutter": ("l2a_bess", "chain_l2a_bess_f"),
    "L2-B destination occupied": ("l2b_habitat", "chain_l2b_habitat_f clears the stand, chain_b_consumables delivers (F112 §7)"),
    "L3 BESS module failed": ("l3_bess", "chain_l3_bess_f"),
    "L3 ISRU filter clogged": ("l3_isru", "chain_l3_isru_f"),
    "L4 spare failed, cannibalize": ("l4_far", "chain_l4_far_f"),
}
CALL = {"navigate_to_feature": "nav", "dock_at_feature": "dock", "pick": "pick", "place": "place", "stow": "stow",
        "navigate_to_pose": "home"}
PLEXIL = {("start", "nav"), ("nav", "dock"), ("dock", "pick"), ("pick", "nav"), ("dock", "place"), ("place", "stow"),
          ("dock", "press[reset]"), ("press[reset]", "stow"), ("stow", "home")}
EUROPA_CALLS = {"nav", "dock", "pick", "place", "stow", "home", "press[reset]"}


def call(name, args):
    if name == "press":
        return "press[shutter]" if args["feature"].endswith("cover_button") else "press[reset]"
    return CALL[name]


def europa(t):
    return t[0] in EUROPA_CALLS | {"start"} and t[1] in EUROPA_CALLS


print("# preplanned_transition_fraction (preregistration §1), computed offline 2026-09-30\n")
print("Rule and sources: `evaluation/preplanned_fraction.py` docstring. Ours 0 on every instance (by construction); "
      "both baselines 1.0 on every covered instance (by construction).\n")
print("| held-out instance | solution (live run) | transitions | PLEXIL | EUROPA -> PLEXIL | missing for PLEXIL | missing for EUROPA |")
print("|---|---|---|---|---|---|---|")
for inst, (chain, run) in INSTANCES.items():
    calls = [call(c[0], c[1] if len(c) > 1 else {}) for c in json.loads((CHAINS / f"{chain}.json").read_text())]
    if chain == "l4_far":
        donor = [i for i, c in enumerate(calls) if c == "pick"][1]
        calls.insert(donor, "authorize")
    s = ["start"] + calls
    ts = list(zip(s, s[1:]))
    p = [t for t in ts if t not in PLEXIL]
    e = [t for t in ts if not europa(t)]
    fmt = lambda miss: ", ".join(f"{a}->{b}" + (f" x{n}" if n > 1 else "") for (a, b), n in Counter(miss).items()) or "none"
    print(f"| {inst} | `{chain}.json` ({run}) | {len(ts)} | {1 - len(p) / len(ts):.2f} ({len(ts) - len(p)}/{len(ts)}) | "
          f"{1 - len(e) / len(ts):.2f} ({len(ts) - len(e)}/{len(ts)}) | {fmt(p)} | {fmt(e)} |")
