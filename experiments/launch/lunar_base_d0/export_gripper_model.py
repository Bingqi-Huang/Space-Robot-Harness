"""Export the simulated EG2 collision meshes and joint geometry to MoveIt's URDF.

Robot asset geometry only; no scene object, grasp coordinates or recorded trajectory.
Run with the repository Python (usd-core). Generated files belong to rm_75_config.
"""
from pathlib import Path
import math
import struct
import xml.etree.ElementTree as ET

import numpy as np
from pxr import Gf, Usd, UsdGeom, UsdPhysics


ROOT = Path(__file__).resolve().parents[3]
ASSET = ROOT / "space_robotics_bench/assets/srb_assets/robot/mobile_manipulation/lunarbot/lunarbot.usdc"
PACKAGE = ROOT / "openral/packages/rm_75_config"


def main():
    stage = Usd.Stage.Open(str(ASSET))
    cache = UsdGeom.XformCache()
    robot = ET.Element("robot", {"xmlns:xacro": "http://www.ros.org/wiki/xacro"})
    robot.append(ET.Comment("Generated by export_gripper_model.py from lunarbot.usdc collision meshes and joints."))
    macro = ET.SubElement(robot, "xacro:macro", name="eg2_collision_model")
    directory = PACKAGE / "meshes/eg2"
    directory.mkdir(parents=True, exist_ok=True)
    root = stage.GetPrimAtPath("/LunarRover/gripper")
    for body in root.GetChildren():
        if not body.HasAPI(UsdPhysics.RigidBodyAPI):
            continue
        link = ET.SubElement(macro, "link", name=body.GetName())
        triangles = []
        for prim in Usd.PrimRange(body, Usd.TraverseInstanceProxies()):
            if not prim.IsA(UsdGeom.Mesh) or "/collisions/" not in str(prim.GetPath()):
                continue
            mesh = UsdGeom.Mesh(prim)
            transform = cache.GetLocalToWorldTransform(prim) * cache.GetLocalToWorldTransform(body).GetInverse()
            vertices = np.array([transform.Transform(Gf.Vec3d(*map(float, p))) for p in mesh.GetPointsAttr().Get()])
            offset = 0
            indices = mesh.GetFaceVertexIndicesAttr().Get()
            for count in mesh.GetFaceVertexCountsAttr().Get():
                face = indices[offset:offset + count]
                for k in range(1, count - 1):
                    triangles.append(vertices[[face[0], face[k], face[k + 1]]])
                offset += count
        path = directory / f"{body.GetName()}.stl"
        with path.open("wb") as output:
            output.write(b"USD collision mesh in rigid-body coordinates".ljust(80, b"\0"))
            output.write(struct.pack("<I", len(triangles)))
            for tri in triangles:
                normal = np.cross(tri[1] - tri[0], tri[2] - tri[0])
                length = np.linalg.norm(normal)
                if length:
                    normal /= length
                output.write(struct.pack("<12fH", *normal, *tri.ravel(), 0))
        geometry = ET.SubElement(ET.SubElement(link, "collision"), "geometry")
        ET.SubElement(geometry, "mesh", filename=f"package://rm_75_config/meshes/eg2/{path.name}")
    mount = ET.SubElement(macro, "joint", name="link7_to_gripper", type="fixed")
    ET.SubElement(mount, "parent", link="Link7")
    ET.SubElement(mount, "child", link="eg2_base")
    # The authored mount has identity local frames, verified rather than inferred.
    fixed = UsdPhysics.FixedJoint(stage.GetPrimAtPath("/LunarRover/joints/gripper_mount"))
    assert tuple(fixed.GetLocalPos0Attr().Get()) == tuple(fixed.GetLocalPos1Attr().Get()) == (0, 0, 0)
    assert fixed.GetLocalRot0Attr().Get() == fixed.GetLocalRot1Attr().Get() == Gf.Quatf(1)
    for prim in stage.GetPrimAtPath("/LunarRover/gripper/joints").GetChildren():
        joint = UsdPhysics.RevoluteJoint(prim)
        parent = joint.GetBody0Rel().GetTargets()[0].name
        child = joint.GetBody1Rel().GetTargets()[0].name
        # These EG2 joints have equal frame rotations and a zero child anchor.
        assert joint.GetLocalRot0Attr().Get() == joint.GetLocalRot1Attr().Get()
        assert tuple(joint.GetLocalPos1Attr().Get()) == (0, 0, 0)
        axis = np.eye(3)["XYZ".index(joint.GetAxisAttr().Get())]
        axis = Gf.Rotation(joint.GetLocalRot0Attr().Get()).TransformDir(Gf.Vec3d(*axis))
        node = ET.SubElement(macro, "joint", name=prim.GetName(), type="revolute")
        ET.SubElement(node, "parent", link=parent)
        ET.SubElement(node, "child", link=child)
        ET.SubElement(node, "origin", xyz=" ".join(map(str, joint.GetLocalPos0Attr().Get())), rpy="0 0 0")
        ET.SubElement(node, "axis", xyz=" ".join(map(str, axis)))
        # Passive in MoveIt; the HAL owns actuation. Limits come from the asset.
        ET.SubElement(node, "limit", lower=str(math.radians(joint.GetLowerLimitAttr().Get())),
                      upper=str(math.radians(joint.GetUpperLimitAttr().Get())), effort="0", velocity="0")
    ET.indent(robot)
    ET.ElementTree(robot).write(PACKAGE / "config/eg2_collision.xacro", encoding="unicode", xml_declaration=True)
    print(f"Exported {len(list(directory.glob('*.stl')))} body meshes and six joints")


if __name__ == "__main__":
    main()
